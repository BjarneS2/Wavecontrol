    def _stream_loop(self, start_seg: int, total_segs: int) -> None:
        try:
            psutil.Process(os.getpid()).nice(psutil.REALTIME_PRIORITY_CLASS)
        except Exception:
            pass

        if (
            self._stream_freqs_kt is None
            or self._stream_amps_kt is None
            or self._stream_dt_arr is None
            or self._stream_cores is None
        ):
            return
        changed = self._stream_changed

        K = self._stream_freqs_kt.shape[0]
        # Worst case per segment. Deliberately NOT reduced by the changed-mask:
        # budgeting conservatively can only under-fill the FIFO (the outer loop comes
        # round again), whereas under-estimating it would overflow the queue.
        cmds_per_seg = 2 + 4 * K + 1  # timer + TIMER trg_src + K*(f,a,df,da) + exec
        n_park_reinit = (2 + 4 * K + 1) + (1 + 5 * K + 1)  # park + re-init overhead
        seg_idx = start_seg
        assert self._stop_event is not None, (
            "_stop_event should have been set by move()"
        )
        while not self._stop_event.is_set():
            if self.card is None or self.dds is None:
                break

            # Query available FIFO space (busy-wait: no sleep)
            try:
                if self._queue_max_actual is not None:
                    avail = self._queue_max_actual - int(
                        self.card.get_i(spcm.SPC_DDS_QUEUE_CMD_COUNT)
                    )
                else:
                    total_c = int(self.dds.queue_cmd_max())  # trying to query again
                    current_queue = int(self.card.get_i(spcm.SPC_DDS_QUEUE_CMD_COUNT))
                    avail = total_c - current_queue
            except Exception as e:
                print(e)
                avail = cmds_per_seg  # conservative fallback: assume one slot free

            avail_for_segs = max(0, avail - n_park_reinit)
            segs_to_push = avail_for_segs // cmds_per_seg
            if segs_to_push == 0:
                time.sleep(0.001)
                continue  # FIFO full — keep polling

            built = 0
            hit_end = False
            while built < segs_to_push and not self._stop_event.is_set():
                if seg_idx >= total_segs:
                    hit_end = True
                    break

                i = seg_idx
                self.dds.trg_timer(float(self._stream_dt_arr[i]) * units.s)
                # source is already TIMER (armed by the init group in _arm_and_stream)
                for k, c in enumerate(self._stream_cores):
                    if changed is not None and not changed[k, i]:
                        continue  # core still holds this exact state
                    df = self._stream_freqs_kt[k, i + 1] - self._stream_freqs_kt[k, i]
                    da = self._stream_amps_kt[k, i + 1] - self._stream_amps_kt[k, i]
                    self._program_segment_core(
                        c,
                        self._stream_freqs_kt[k, i],
                        self._stream_amps_kt[k, i],
                        df,
                        da,
                        self._stream_dt_arr[i],
                    )
                self.dds.exec_at_trg()
                built += 1
                seg_idx += 1

            if built > 0:
                self.dds.write_to_card()  # flush segment batch first

            if hit_end:
                # Timer-based park: fires dt[-1] after the last ramp completes (that timer
                # was written by the last segment group). What THIS group writes gates the
                # group after it: NONE stops the timer for a single shot; CARD makes the
                # re-init group below wait for EXT0.
                self.dds.trg_src(spcm.SPCM_DDS_TRG_SRC_CARD)
                for k, c in enumerate(self._stream_cores):
                    c.freq(float(self._stream_freqs_kt[k, -1]) * units.Hz)
                    c.amp(float(self._stream_amps_kt[k, -1]))
                    c.freq_slope(0)
                    c.amp_slope(0)
                self.dds.exec_at_trg()

                if self._stream_continuous:
                    # Re-queue initial state: switch to CARD trigger and wait for EXT0.
                    # Flushed immediately and separately from the segment batch above
                    # to guarantee trg_src=CARD lands in the hardware FIFO with
                    # confirmed space (reserved via avail_for_segs above).
                    # This group is the one that waits for EXT0 (the park group armed CARD).
                    # It in turn arms TIMER + dt[0] for the first segment of the next cycle.
                    self.dds.trg_timer(float(self._stream_dt_arr[0]) * units.s)
                    self.dds.trg_src(spcm.SPCM_DDS_TRG_SRC_TIMER)
                    for k, c in enumerate(self._stream_cores):
                        c.freq(float(self._stream_freqs_kt[k, 0]) * units.Hz)
                        c.amp(float(self._stream_amps_kt[k, 0]))
                        c.phase(
                            self._phase_deg(self._stream_phases[k])
                            if self._stream_phases is not None
                            else 0.0
                        )
                        c.freq_slope(0)
                        c.amp_slope(0)
                    self.dds.exec_at_trg()
                    self.dds.write_to_card()  # flush park+re-init as its own batch
                    seg_idx = 0  # restart trajectory on next EXT0
                else:
                    self.dds.write_to_card()
                    return  # single-shot: all segments queued, exit thread

        return

    def stop(self, park: bool = True) -> None:
        """Tear down any streaming thread; with park=True also zero every core and stop.

        park=False skips the zero-park and its 10 ms settle, leaving whatever the card is
        currently emitting in place. Use it when the next thing you do is re-arm, as
        Sorter1D.revert() does: _program_static_cores() stops the card itself, so parking
        to zero first only inserts >10 ms of darkness between the sorted block and the
        re-armed array for no benefit."""
        if self._stop_event is not None:
            self._stop_event.set()
        if self._stream_thread is not None:
            self._stream_thread.join(timeout=5.0)
        self._stream_thread = None
        self._stop_event = None
        self._stream_freqs_kt = None
        self._stream_amps_kt = None
        self._stream_dt_arr = None
        self._stream_phases = None
        self._stream_cores = None
        self._stream_changed = None

        if not park:
            return  # leave the card emitting; the caller re-arms straight over the top

        if self.dds is not None and self.card is not None:
            self.card.stop(spcm.M2CMD_CARD_STOP)
            self._card_started = False
            self.dds.reset()
            f_park = 0.5 * (self.f_min_hz + self.f_max_hz)
            for core in self.dds:
                core.amp(0)
                core.freq(f_park * units.Hz)
                core.freq_slope(0)
                core.amp_slope(0)
            self.dds.exec_at_trg()
            self.dds.write_to_card()
            self.card.start(spcm.M2CMD_CARD_ENABLETRIGGER, spcm.M2CMD_CARD_FORCETRIGGER)
            time.sleep(0.01)
            self.card.stop()
            self._card_started = False
        return

    def _static_setpoints(self, positions_um, occupancy, channel, amplitudes, phases):
        positions_um = np.asarray(positions_um, dtype=float)
        occupancy = np.asarray(occupancy, dtype=bool)
        N = len(positions_um)
        if len(occupancy) != N:
            raise ValueError("positions_um and occupancy must have the same length.")

        n_active = int(occupancy.sum())
        core_indices = self._select_cores(channel, N)

        freqs = convert_position_to_freq(
            positions_um[np.newaxis, :],
            f_start_hz=self.f_start_hz,
            um_per_MHz=self.um_per_MHz,
        )[0]
        if np.any(freqs < self.f_min_hz) or np.any(freqs > self.f_max_hz):
            raise ValueError(
                f"Frequencies outside AOD band "
                f"[{self.f_min_hz / 1e6:.1f}, {self.f_max_hz / 1e6:.1f}] MHz. "
                f"Got [{freqs.min() / 1e6:.3f}, {freqs.max() / 1e6:.3f}] MHz."
            )

        if amplitudes is None:
            amp_per = self.max_total_amplitude / max(n_active, 1)
            amps_set = np.where(occupancy, amp_per, 0.0)
        elif np.isscalar(amplitudes):
            amps_set = np.where(occupancy, float(amplitudes), 0.0)  # type: ignore
        else:
            amplitudes = np.asarray(amplitudes, dtype=float)
            if amplitudes.shape == (N,):
                amps_set = np.where(occupancy, amplitudes, 0.0)
            elif amplitudes.shape == (n_active,):
                full_amp = np.zeros(N)
                full_amp[occupancy] = amplitudes
                amps_set = full_amp
            else:
                raise ValueError(
                    f"amplitudes shape {amplitudes.shape} invalid for N={N}, n_active={n_active}."
                )

        phases_r = self._resolve_phases(
            phases, N
        )  # assigned by ascending-frequency rank
        sort_order = np.argsort(freqs)
        entries = [
            (core_indices[rank], freqs[si], amps_set[si], phases_r[rank])
            for rank, si in enumerate(sort_order)
        ]
        state = {
            "positions_um": positions_um.copy(),
            "freqs_hz": freqs.copy(),
            "amps": amps_set.copy(),
            "occupancy": occupancy.copy(),
            "sort_order": sort_order.copy(),
            "core_indices": list(core_indices),
        }
        return entries, amps_set, n_active, N, core_indices, state

    def program_static(
        self,
        positions_um: np.ndarray,
        occupancy: np.ndarray,
        channel: int = 0,
        amplitudes: float | np.ndarray | None = None,
        phases: np.ndarray | None = None,
    ) -> np.ndarray:
        """
        Set DDS cores to static (non-moving) tones.

        Cores are assigned in ascending frequency order: the site with the lowest
        frequency gets core 0, the next gets core 1, and so on.
        Occupied sites get the given amplitude; empty sites get amplitude 0.

        Stores soft state in self._static_core_state[channel] for later use.

        Args:
            positions_um: (N,) trap positions [µm].
            occupancy:    (N,) bool — True where an atom is present.
            channel:      0 (X-AOD) or 1 (Y-AOD).
            amplitudes:   None → equal share of max_total_amplitude.
                          Scalar, (N,), or (n_active,) array.
            phases:       None → 0. (N,) initial phases [rad] assigned by ascending
                          frequency rank (e.g. schroeder_generalized(N) for IMD suppression).

        Returns:
            amps_set: (N,) amplitudes programmed, in the same order as positions_um.
        """
        if self.card is None or self.dds is None:
            raise RuntimeError("Card not connected. Call connect() first.")

        entries, amps_set, n_active, N, core_indices, state = self._static_setpoints(
            positions_um, occupancy, channel, amplitudes, phases
        )
        self._program_static_cores(entries)
        self._static_core_state[channel] = state

        print(
            f"[AWGController] Static tones: {n_active}/{N} occupied, CH{channel}, "
            f"cores {core_indices[0]}..{core_indices[-1]}.\n"
        )
        return amps_set

    def program_static_2d(
        self,
        positions_ch0: np.ndarray,
        occupancy_ch0: np.ndarray,
        positions_ch1: np.ndarray,
        occupancy_ch1: np.ndarray,
        amplitudes_ch0=None,
        amplitudes_ch1=None,
        phases_ch0=None,
        phases_ch1=None,
    ):
        """Program static tones on BOTH outputs in a single reset/exec (X + Y AODs)."""
        if self.card is None or self.dds is None:
            raise RuntimeError("Card not connected. Call connect() first.")

        e0, a0, n0, N0, _, s0 = self._static_setpoints(
            positions_ch0, occupancy_ch0, 0, amplitudes_ch0, phases_ch0
        )
        e1, a1, n1, N1, _, s1 = self._static_setpoints(
            positions_ch1, occupancy_ch1, 1, amplitudes_ch1, phases_ch1
        )
        self._program_static_cores(e0 + e1)
        self._static_core_state[0] = s0
        self._static_core_state[1] = s1

        print(
            f"[AWGController] Static tones (2D): CH0 {n0}/{N0}, CH1 {n1}/{N1} occupied.\n"
        )
        return a0, a1

    def tones_on_grid(self, f0_req=100e6, df_req=1e6, n_tones=20):
        assert self.card is not None, "Card not connected. Call connect() first.\n"
        f_step = self.card.get_d(spcm.SPC_DDS_AVAIL_FREQ_STEP)

        print(f"f_step, {f_step}")

        n0 = round(f0_req / f_step)
        dn = round(df_req / f_step)

        f0 = n0 * f_step
        df = dn * f_step

        freqs = [f0 + k * df for k in range(n_tones)]

        return freqs

    def dds_freq_step_hz(self) -> float:
        """The card's DDS frequency grid resolution [Hz] (SPC_DDS_AVAIL_FREQ_STEP).
        Only requestable frequencies are integer multiples of this. Call connect() first."""
        assert self.card is not None, "Card not connected. Call connect() first.\n"
        return float(self.card.get_d(spcm.SPC_DDS_AVAIL_FREQ_STEP))

    def snap_freqs_to_grid(self, freqs_hz) -> np.ndarray:
        """Round each requested frequency to the nearest settable DDS grid point. Snapping
        the start frequency and using a spacing that is an exact integer multiple of the grid
        step keeps a multi-tone array exactly equally spaced, removing the slow power beating
        that off-grid rounding residuals produce."""
        step = self.dds_freq_step_hz()
        return np.round(np.asarray(freqs_hz, dtype=float) / step) * step
